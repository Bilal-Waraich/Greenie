/**
 * Unit tests for the badges.json and guide.json rules (scripts/lib/badges-rules.mjs,
 * scripts/lib/guide-rules.mjs) and the badges SQL generator (scripts/badges-to-sql.mjs).
 * Run with `npm run test:unit` in frontend/. The database applies the badge rules again
 * (supabase/tests/database/badges.test.sql).
 */
import assert from 'node:assert/strict'
import { join } from 'node:path'
import { test } from 'node:test'
import { buildBadgesSql } from '../badges-to-sql.mjs'
import { validateBadges } from '../lib/badges-rules.mjs'
import { validateGuide } from '../lib/guide-rules.mjs'
import { readJsonFile } from '../lib/read-json.mjs'

/**
 * Returns a valid badge, with optional changes.
 * @param {object} [changes]
 * @returns {object}
 */
function badge(changes = {}) {
  return { key: 'test_badge', label: 'Test badge', rule: 'points', threshold: 100, ...changes }
}

/**
 * Returns a valid guide entry, with optional changes.
 * @param {object} [changes]
 * @returns {object}
 */
function entry(changes = {}) {
  return { item: 'PET bottles', where: 'Back to the shop', note: 'Return them.', ...changes }
}

test('the repository badges.json and guide.json pass', () => {
  for (const [file, validate] of [['badges.json', validateBadges], ['guide.json', validateGuide]]) {
    const result = readJsonFile(join(import.meta.dirname, '..', '..', file))
    assert.equal(result.ok, true, file)
    assert.deepEqual(validate(result.value), [], file)
  }
})

test('badges: a valid list passes; the list must be a non-empty array of objects', () => {
  assert.deepEqual(validateBadges([badge(), badge({ key: 'other', rule: 'streak', threshold: 7 })]), [])
  assert.deepEqual(validateBadges({}), ['badges.json must be a list (a JSON array) of badges.'])
  assert.deepEqual(validateBadges([]), ['badges.json must contain at least one badge.'])
  assert.match(validateBadges(['x'])[0], /entry 1 must be an object/)
})

test('badges: missing and unknown fields, keys, labels, rules and thresholds are checked', () => {
  const missing = badge()
  delete missing.rule
  assert.match(validateBadges([missing]).join(), /missing the field "rule"/)
  assert.match(validateBadges([badge({ icon: 'x' })]).join(), /unknown field "icon"/)
  assert.match(validateBadges([badge({ key: 'Bad Key' })]).join(), /"key" must be/)
  assert.match(validateBadges([badge(), badge()]).join(), /used more than once/)
  assert.match(validateBadges([badge({ label: ' ' })]).join(), /"label" must be text of 1 to 100/)
  assert.match(validateBadges([badge({ label: 'x'.repeat(101) })]).join(), /"label"/)
  assert.match(validateBadges([badge({ rule: 'visits' })]).join(), /"rule" must be "logs", "points" or "streak"/)
  for (const bad of [0, -1, 2.5, '7', null]) {
    assert.match(validateBadges([badge({ threshold: bad })]).join(), /"threshold" must be a whole number of at least 1/, `threshold=${bad}`)
  }
  assert.match(validateBadges([badge(), badge({ key: 'second', threshold: 0 })])[0], /entry 2 \("second"\)/)
})

test('guide: a valid list passes; item and where must be text, note may be empty', () => {
  assert.deepEqual(validateGuide([entry(), entry({ note: '' })]), [])
  assert.deepEqual(validateGuide([]), ['guide.json must contain at least one entry.'])
  assert.deepEqual(validateGuide('x'), ['guide.json must be a list (a JSON array) of entries.'])
  assert.match(validateGuide([entry({ item: '' })]).join(), /"item" must be text, not empty/)
  assert.match(validateGuide([entry({ where: '  ' })]).join(), /"where" must be text, not empty/)
  assert.match(validateGuide([entry({ note: 5 })]).join(), /"note" must be text/)
  assert.match(validateGuide([entry({ extra: 'x' })]).join(), /unknown field "extra"/)
  assert.match(validateGuide([entry(), entry({ where: '' })])[0], /entry 2 \("PET bottles"\)/)
})

test('buildBadgesSql wraps the JSON in one sync call and refuses the quote tag', () => {
  assert.match(buildBadgesSql([badge()]), /^-- Generated by scripts\/badges-to-sql\.mjs from badges\.json/)
  assert.match(buildBadgesSql([badge()]), /select private\.sync_badges\(\$greenie\$\[\{"key":"test_badge".*\}\]\$greenie\$::jsonb\);/)
  assert.throws(() => buildBadgesSql([badge({ label: 'a $greenie$ b' })]), /badges\.json must not contain/)
})
