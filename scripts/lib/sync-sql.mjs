/**
 * Builds the SQL that loads one of the client's JSON files into the database, and the command-line
 * part shared by scripts/actions-to-sql.mjs and scripts/badges-to-sql.mjs.
 *
 * The SQL is a single call to a private.sync_* function with the file's content as a dollar-quoted
 * JSON literal. The database function validates the list again and updates its table.
 */
import { readJsonFile } from './read-json.mjs'

/** Dollar-quote tag around the JSON literal. The JSON must never contain it. */
const QUOTE_TAG = '$greenie$'

/**
 * Builds the SQL statement for a validated list.
 * @param {{ file: string, script: string, functionName: string, list: unknown[] }} options
 *   - file: the JSON file's name; script: the generating script's name (for the comment line);
 *   functionName: the database function, for example "private.sync_actions"; list: the parsed content.
 * @returns {string} The SQL statement.
 * @throws {Error} If the JSON contains the quote tag.
 */
export function buildSyncSql({ file, script, functionName, list }) {
  const json = JSON.stringify(list)
  if (json.includes(QUOTE_TAG)) {
    throw new Error(`${file} must not contain the text ${QUOTE_TAG}.`)
  }
  return [
    `-- Generated by scripts/${script} from ${file}. Do not edit.`,
    `select ${functionName}(${QUOTE_TAG}${json}${QUOTE_TAG}::jsonb);`,
    '',
  ].join('\n')
}

/**
 * Reads and validates a JSON file and prints its SQL, or exits with code 1 on any problem.
 * @param {{ path: string, file: string, validate: (value: unknown) => string[], build: (list: unknown[]) => string }} options
 *   - path: where to read the file; file: its name for messages; validate: returns the problems;
 *   build: turns the valid list into SQL.
 * @returns {void}
 */
export function printSyncSql({ path, file, validate, build }) {
  const result = readJsonFile(path)
  const errors = result.ok ? validate(result.value) : [result.error]
  if (errors.length > 0) {
    console.error(`Not loading ${file} (${path}):`)
    for (const error of errors) console.error(`  - ${error}`)
    process.exit(1)
  }
  try {
    process.stdout.write(build(result.value))
  } catch (error) {
    console.error(error.message)
    process.exit(1)
  }
}
