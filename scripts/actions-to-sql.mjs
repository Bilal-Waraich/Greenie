/**
 * Prints the SQL that loads actions.json into the database (US-08).
 *
 * Usage: node scripts/actions-to-sql.mjs [path/to/actions.json] | psql "<database url>" -v ON_ERROR_STOP=1
 *
 * The output is a single call to private.sync_actions(...) with the file's content as a dollar-quoted
 * JSON literal. The database function validates the list again, updates or adds every action, and
 * hides actions that are no longer in the file. The deploy workflow and `npm run db:reset` both use it.
 * No dependencies: plain Node.js.
 */
import { join } from 'node:path'
import { validateActions } from './lib/actions-rules.mjs'
import { readJsonFile } from './lib/read-json.mjs'

/** Dollar-quote tag around the JSON literal. The JSON must never contain it. */
const QUOTE_TAG = '$greenie$'

/**
 * Builds the SQL statement for a validated action list.
 * @param {unknown[]} actions - Parsed and validated actions.json content.
 * @returns {string} The SQL statement.
 */
export function buildActionsSql(actions) {
  const json = JSON.stringify(actions)
  if (json.includes(QUOTE_TAG)) {
    throw new Error(`actions.json must not contain the text ${QUOTE_TAG}.`)
  }
  return [
    '-- Generated by scripts/actions-to-sql.mjs from actions.json. Do not edit.',
    `select private.sync_actions(${QUOTE_TAG}${json}${QUOTE_TAG}::jsonb);`,
    '',
  ].join('\n')
}

/**
 * Reads, validates and prints the SQL, or exits with code 1 on any problem.
 * @returns {void}
 */
function main() {
  const actionsPath = process.argv[2] || join(import.meta.dirname, '..', 'actions.json')
  const result = readJsonFile(actionsPath)
  const errors = result.ok ? validateActions(result.value) : [result.error]
  if (errors.length > 0) {
    console.error(`Not loading actions (${actionsPath}):`)
    for (const error of errors) console.error(`  - ${error}`)
    process.exit(1)
  }
  try {
    process.stdout.write(buildActionsSql(result.value))
  } catch (error) {
    console.error(error.message)
    process.exit(1)
  }
}

if (process.argv[1] && import.meta.filename === process.argv[1]) {
  main()
}
